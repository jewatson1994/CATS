#!/usr/bin/env python3
"""Guided Linux deployment of the shipped main or replica Compose template.

Uses Python's standard library, Docker Engine/Compose v2 and openssl. It never
installs OS packages, deletes volumes, or disables host security policy.
"""
import argparse
import base64
from datetime import datetime, timezone
import getpass
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import shlex
import shutil
import ssl
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
WORKERS = ("discovery-worker", "scan-worker", "patch-worker", "remediation-worker")
PROFILE = "cats-worker-actions"
DOCKER_ENDPOINT = None


class SetupError(Exception):
    pass


def ask(label, default="", secret=False):
    suffix = " [Enter keeps existing value]" if secret and default else (
        " [" + default + "]" if default else "")
    reader = getpass.getpass if secret else input
    value = reader(label + suffix + ": ").strip()
    value = value or default
    if any(c in value for c in ("\x00", "\r", "\n")):
        raise SetupError("Settings must be single-line values.")
    return value


def yes(label, default=True):
    while True:
        value = input(label + (" [Y/n]: " if default else " [y/N]: ")).strip().lower()
        if not value:
            return default
        if value in ("yes", "y", "no", "n"):
            return value in ("yes", "y")
        print("Please enter yes or no.")


def run(argv, *, env=None, capture=True):
    # Do not echo commands/output on failure: Compose/registry errors can contain secrets.
    if argv[0] == "docker" and DOCKER_ENDPOINT:
        if argv[1:2] != ["--host"]:
            argv = ["docker", "--host", DOCKER_ENDPOINT] + list(argv[1:])
        env = dict(os.environ if env is None else env)
        for key in ("DOCKER_HOST", "DOCKER_CONTEXT", "DOCKER_TLS", "DOCKER_TLS_VERIFY", "DOCKER_CERT_PATH"):
            env.pop(key, None)
    try:
        result = subprocess.run([str(a) for a in argv], env=env, text=True,
                                capture_output=capture, check=False)
    except OSError as exc:
        raise SetupError("Cannot execute " + str(argv[0]) + ": " + str(exc)) from exc
    if result.returncode:
        raise SetupError("Command failed: " + str(argv[0]) + " (exit " + str(result.returncode)
                         + "). Check the named dependency or saved deployment's health/logs.")
    return result.stdout if capture else ""


def parse_env(text):
    """Read literal one-line Compose env settings, without executing shell input.

    Reject interpolation rather than silently changing an existing deployment's
    credentials. Single-quoted dollar signs remain literal and are supported.
    """
    values = {}
    for number, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)", line)
        if not match:
            raise SetupError(f"Unsupported environment syntax at line {number}; use literal KEY=value settings.")
        key, value = match.groups()
        if key in values:
            raise SetupError(f"Duplicate setting {key}; remove the ambiguity before setup.")
        if value.startswith("'"):
            quoted = re.fullmatch(r"'((?:\\'|[^'])*)'\s*(?:#.*)?", value)
            if not quoted:
                raise SetupError(f"Unsupported quoted value for {key}.")
            value = quoted[1].replace("\\'", "'")
        else:
            if value.startswith('"'):
                quoted = re.fullmatch(r'"((?:\\.|[^"\\])*)"\s*(?:#.*)?', value)
                if not quoted:
                    raise SetupError(f"Unsupported quoted value for {key}.")
                value = re.sub(r'\\([\\"nrt])', lambda m: {
                    "n": "\n", "r": "\r", "t": "\t"}.get(m[1], m[1]), quoted[1])
            else:
                value = re.split(r"\s+#", value, maxsplit=1)[0].rstrip()
            literal = value.replace("$$", "\x01")
            if "$" in literal:
                raise SetupError(f"{key} uses interpolation. Resolve it to a literal value first; quote literal dollar signs with single quotes.")
            value = literal.replace("\x01", "$")
        if any(c in value for c in ("\x00", "\r", "\n")):
            raise SetupError(f"Multiline values are unsupported for {key}.")
        values[key] = value
    return values


def serialize_env(values):
    # Double quotes handle trailing backslashes; $$ prevents Compose interpolation.
    return "# Generated by CATS setup. Contains secrets; preserve for upgrades and recovery.\n" + "".join(
        key + "=" + json.dumps(value, ensure_ascii=False).replace("$", "$$") + "\n"
        for key, value in values.items())


def private_write(path, text, mode=0o600):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    if path.is_symlink():
        raise SetupError("Refusing to replace a symbolic link: " + str(path))
    descriptor, temporary = tempfile.mkstemp(prefix=".cats-", dir=path.parent)
    try:
        os.fchmod(descriptor, mode) if hasattr(os, "fchmod") else os.chmod(temporary, mode)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def clean_environment(values):
    # Shell variables otherwise silently override --env-file, even on a rerun.
    return {k: v for k, v in os.environ.items()
            if k not in values and not k.startswith(("CATS_", "COMPOSE_", "POSTGRES_", "INTELLIGENCE_POSTGRES_"))
            and k != "PIPELINE_API_TOKEN"}


def verify_bundle(root, mode):
    manifest_path = root / "manifest.json"
    if not manifest_path.exists():
        return {}
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 1 or manifest.get("mode") != mode:
        raise SetupError("This bundle is for a different mode or unsupported manifest version.")
    files = manifest.get("files")
    if not isinstance(files, dict) or not files:
        raise SetupError("Bundle has no file checksums.")
    for name, expected in files.items():
        path = (root / name).resolve()
        if not path.is_relative_to(root.resolve()) or not path.is_file():
            raise SetupError("Missing or unsafe bundle file: " + name)
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(4 * 1024 * 1024), b""):
                digest.update(block)
        if digest.hexdigest() != expected:
            raise SetupError("Bundle checksum failed: " + name)
    print("Bundle file checksums verified. Trust the bundle's original delivery channel separately.")
    return manifest


def docker_host():
    if sys.platform != "linux":
        raise SetupError("Run this installer on the Linux Docker host. Build/transfer the bundle from other systems.")
    for executable in ("docker", "openssl"):
        if not shutil.which(executable):
            raise SetupError(executable + " is required. Install it from your approved OS media first.")
    version = run(["docker", "compose", "version", "--short"]).strip().lstrip("v")
    if not re.match(r"[2-9]\.", version):
        raise SetupError("Docker Compose v2 or later is required.")
    context_name = os.environ.get("DOCKER_CONTEXT")
    endpoint = None if context_name else os.environ.get("DOCKER_HOST")
    if not endpoint:
        context = json.loads(run(["docker", "context", "inspect"] + ([context_name] if context_name else [])))[0]
        endpoint = context["Endpoints"]["docker"]["Host"]
    if not endpoint.startswith("unix://"):
        raise SetupError("Use a local Docker context: certificates, mounts and AppArmor must be on the Docker host.")
    info = json.loads(run(["docker", "info", "--format", "{{json .}}"] ))
    security = " ".join(info.get("SecurityOptions") or [])
    if info.get("OSType") != "linux" or "rootless" in security or "Docker Desktop" in info.get("OperatingSystem", ""):
        raise SetupError("This host installer requires rootful Docker Engine on Linux. Desktop/rootless deployments need separate host qualification.")
    info["_SetupEndpoint"] = endpoint
    return info


def hostname(value):
    if "." not in value or len(value) > 253 or not re.fullmatch(r"[a-zA-Z0-9](?:[a-zA-Z0-9.-]*[a-zA-Z0-9])?", value):
        raise SetupError("Enter a DNS hostname without https://, a port, wildcard, or path.")
    if any(not label or len(label) > 63 or label.startswith("-") or label.endswith("-") for label in value.split(".")):
        raise SetupError("Invalid DNS hostname.")
    return value.lower()


def certificate(directory, name):
    directory = Path(directory).expanduser().resolve()
    cert, key = directory / "tls.crt", directory / "tls.key"
    if not cert.is_file() or not key.is_file():
        raise SetupError(f"Place the full-chain tls.crt and tls.key in {directory} and rerun.")
    try:
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(str(cert), str(key), password=lambda: "")
    except (ssl.SSLError, OSError) as exc:
        raise SetupError(f"Certificate/key mismatch, unreadable file or encrypted server key in {directory}.") from exc
    locale = dict(os.environ, LC_ALL="C")
    run(["openssl", "x509", "-in", cert, "-noout", "-checkend", "0"], env=locale)
    checked = run(["openssl", "x509", "-in", cert, "-noout", "-checkhost", name], env=locale)
    # OpenSSL x509 may exit zero even when the hostname does NOT match.
    if "does match certificate" not in checked:
        raise SetupError(f"Certificate in {directory} does not cover {name}.")
    start = run(["openssl", "x509", "-in", cert, "-noout", "-startdate"], env=locale).strip()
    valid_from = datetime.strptime(start.removeprefix("notBefore="), "%b %d %H:%M:%S %Y %Z").replace(tzinfo=timezone.utc)
    if valid_from > datetime.now(timezone.utc):
        raise SetupError(f"Certificate in {directory} is not valid yet; check certificate dates and the host clock.")
    return str(directory)


def required_secret(values, key, label, *, minimum=24, fernet=False):
    previous = values.get(key, "")
    placeholder = not previous or previous.lower().startswith(("replace", "change-me", "changeme"))
    if placeholder:
        value = ask(label + " (blank generates securely)", secret=True)
        value = value or (base64.urlsafe_b64encode(secrets.token_bytes(32)).decode() if fernet else secrets.token_urlsafe(36))
        values[key] = value
    else:
        value = previous
    if fernet:
        try:
            valid = len(base64.b64decode(value, altchars=b"-_", validate=True)) == 32
        except (ValueError, UnicodeError):
            valid = False
        if not valid:
            raise SetupError("CATS_CONFIG_ENCRYPTION_KEY must be a valid Fernet key; preserve the original key on upgrades.")
    elif len(value) < minimum and (placeholder or key.endswith("TOKEN")):
        raise SetupError(key + f" must contain at least {minimum} characters. Existing values were not changed.")


def default_image(manifest, role, fallback=""):
    if manifest.get("files_only") and fallback:
        return fallback
    return next((row["archive_reference"] for row in manifest.get("images", [])
                 if row["role"] == role and row.get("archive_reference")), fallback)


def gather(mode, existing, manifest):
    example = ROOT / "templates" / (mode + ".env.example")
    values = parse_env(example.read_text(encoding="utf-8-sig"))
    values.update(existing)
    # Preserve an older deployment's node override when introducing the public
    # setting; the example default must not shadow the legacy fallback.
    if mode == "main" and not existing.get("CATS_KIND_NODE_IMAGE") and existing.get("CATS_DEPLOYMENT_KIND_NODE_IMAGE"):
        values["CATS_KIND_NODE_IMAGE"] = existing["CATS_DEPLOYMENT_KIND_NODE_IMAGE"]
    default_project = existing.get("COMPOSE_PROJECT_NAME") or ("cats" if mode == "main" else "cats-replica")
    values["COMPOSE_PROJECT_NAME"] = ask("Compose project name (keep the existing name for upgrades)", default_project)
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", values["COMPOSE_PROJECT_NAME"]):
        raise SetupError("Project name must use lowercase letters, numbers, dashes or underscores.")
    # Both modes run the full release image. Preserve a legacy replica override
    # when introducing CATS_IMAGE; the example value must not shadow it.
    fallback = existing.get("CATS_IMAGE") or (existing.get("CATS_REPLICA_IMAGE", "") if mode == "replica" else "")
    values["CATS_IMAGE"] = ask("Full CATS image tag or digest (shared by main and replica)",
                               default_image(manifest, "cats", fallback))
    if not values["CATS_IMAGE"] or any(c.isspace() for c in values["CATS_IMAGE"]) or values["CATS_IMAGE"].startswith("-"):
        raise SetupError("A valid built full CATS image reference is required.")
    nginx = default_image(manifest, "nginx", existing.get("CATS_NGINX_IMAGE", ""))
    if nginx:
        values["CATS_NGINX_IMAGE"] = nginx
    values["CATS_BOOTSTRAP_USERNAME"] = ask("Administrator username", values.get("CATS_BOOTSTRAP_USERNAME", "admin"))
    for key in ("POSTGRES_DB", "POSTGRES_USER"):
        values[key] = ask(key.replace("_", " ").title(), values.get(key, "cats"))
        if not re.fullmatch(r"[a-zA-Z_][a-zA-Z0-9_]*", values[key]):
            raise SetupError(key + " must be a simple PostgreSQL identifier.")
    # Never regenerate an existing secret. Rotation needs its own application workflow.
    required_secret(values, "POSTGRES_PASSWORD", "Database password")
    required_secret(values, "CATS_BOOTSTRAP_PASSWORD", "Initial administrator password", minimum=12)
    required_secret(values, "CATS_CONFIG_ENCRYPTION_KEY", "Fernet encryption key", fernet=True)
    if mode == "main":
        for key in ("PIPELINE_API_TOKEN", "CATS_PATCH_WORKER_TOKEN", "CATS_SCAN_WORKER_TOKEN"):
            required_secret(values, key, key, minimum=32)
        if len({values[k] for k in ("PIPELINE_API_TOKEN", "CATS_PATCH_WORKER_TOKEN", "CATS_SCAN_WORKER_TOKEN")}) != 3:
            raise SetupError("Use distinct pipeline, patch and scan tokens.")
        values["CATS_KIND_NODE_IMAGE"] = ask("Kind node image tag or digest (optional Deployment Validation)", values["CATS_KIND_NODE_IMAGE"])
        if not values["CATS_KIND_NODE_IMAGE"] or any(c.isspace() for c in values["CATS_KIND_NODE_IMAGE"]) or values["CATS_KIND_NODE_IMAGE"].startswith("-"):
            raise SetupError("A valid Kind node image reference is required; preload it before enabling Deployment Validation.")
    for kind in ("PORTAL", "OCI"):
        key = "CATS_" + kind + "_HOSTNAME"
        values[key] = hostname(ask(kind.title() + " DNS hostname", existing.get(key, "")))
        path_key = "CATS_" + kind + "_CERT_DIR"
        values[path_key] = certificate(ask(kind.title() + " directory containing tls.crt and tls.key", values[path_key]), values[key])
    if values["CATS_PORTAL_HOSTNAME"] == values["CATS_OCI_HOSTNAME"]:
        raise SetupError("Portal and OCI hostnames must be different.")
    if mode == "main":
        for key, label in (("CATS_SCAN_REGISTRY_AUTH_SOURCE", "Scanner registry-auth directory"),
                           ("CATS_DB_BACKUP_DIR", "Database backup directory"),
                           ("CATS_DISCOVERY_MIRROR_DIR", "Discovery mirror directory")):
            path = Path(values[key]).expanduser()
            if not path.is_absolute():
                path = ROOT / "templates" / path
            values[key] = str(Path(ask(label + " (preserve existing storage)", str(path.resolve()))).expanduser().resolve())
    values["CATS_SETUP_CA_FILE"] = ask("Optional CA PEM file for portal/API HTTPS (blank uses system trust)", existing.get("CATS_SETUP_CA_FILE", ""))
    if values["CATS_SETUP_CA_FILE"]:
        path = Path(values["CATS_SETUP_CA_FILE"]).expanduser().resolve()
        ssl.create_default_context(cafile=str(path))
        values["CATS_SETUP_CA_FILE"] = str(path)
    return values


def ensure_no_unclaimed_project(project, existing):
    found = run(["docker", "volume", "ls", "--filter", "label=com.docker.compose.project=" + project, "--format", "{{.Name}}"])
    containers = run(["docker", "ps", "-aq", "--filter", "label=com.docker.compose.project=" + project])
    missing_secrets = any(not existing.get(key) or existing[key].lower().startswith(("replace", "change-me", "changeme"))
                          for key in ("POSTGRES_PASSWORD", "CATS_CONFIG_ENCRYPTION_KEY"))
    if (found.strip() or containers.strip()) and missing_secrets:
        raise SetupError("An existing " + project + " deployment was found. Rerun with --env-file pointing to its original secrets; setup will not create replacement credentials.")


def apparmor_needed(mode, info, *, os_release=Path("/etc/os-release")):
    if mode != "main":
        return False
    security = " ".join(info.get("SecurityOptions") or [])
    if "apparmor" not in security:
        enabled = Path("/sys/module/apparmor/parameters/enabled")
        if enabled.exists() and enabled.read_text().strip().upper() == "Y":
            raise SetupError("Host AppArmor is enabled but Docker does not advertise it. Fix the Docker/host policy integration first.")
        print("Docker has no AppArmor enforcement; the bundled seccomp policy and worker probes remain enabled.")
        return False
    release = parse_env(os_release.read_text())
    if release.get("ID") != "ubuntu" or release.get("VERSION_ID") != "24.04":
        raise SetupError("The supplied AppArmor profile is qualified for Ubuntu 24.04 with AppArmor 4+. Other AppArmor hosts require separate qualification.")
    parser = shutil.which("apparmor_parser") or ("/sbin/apparmor_parser" if Path("/sbin/apparmor_parser").exists() else None)
    if not parser:
        raise SetupError("Install the host AppArmor parser from approved OS media, then rerun.")
    version = run([parser, "--version"])
    match = re.search(r"version\s+(\d+)", version, re.I)
    if not match or int(match[1]) < 4:
        raise SetupError("AppArmor parser 4+ is required.")
    for path in (Path("/proc/sys/user/max_user_namespaces"), Path("/proc/sys/kernel/unprivileged_userns_clone")):
        if path.exists() and int(path.read_text()) == 0:
            raise SetupError("Host policy disables required unprivileged user namespaces: " + str(path))
    return True


def load_apparmor():
    prefix = [] if os.geteuid() == 0 else ["sudo"]
    print("Installing and loading the enforcing worker AppArmor profile on this host.")
    run(prefix + ["install", "-m", "0644", ROOT / "deploy/cats-worker-actions.apparmor", "/etc/apparmor.d/" + PROFILE])
    parser = shutil.which("apparmor_parser") or "/sbin/apparmor_parser"
    run(prefix + [parser, "--replace", "/etc/apparmor.d/" + PROFILE])
    profiles = run(prefix + ["cat", "/sys/kernel/security/apparmor/profiles"])
    if PROFILE + " (enforce)" not in profiles.splitlines():
        raise SetupError("Worker AppArmor profile is not enforcing.")


def compose_command(mode, env_file, values, apparmor, extra):
    command = ["docker"]
    if values.get("CATS_SETUP_DOCKER_HOST"):
        command += ["--host", values["CATS_SETUP_DOCKER_HOST"]]
    command += ["compose", "--env-file", str(env_file), "--project-name", values["COMPOSE_PROJECT_NAME"],
               "-f", str(ROOT / "templates" / ("compose." + mode + ".yaml"))]
    if apparmor:
        command += ["-f", str(ROOT / "deploy/compose.worker-apparmor.yaml")]
    for path in extra:
        if not path.is_file():
            raise SetupError("Missing extra Compose file: " + str(path))
        command += ["-f", str(path.resolve())]
    return command


def write_launcher(path, command, values):
    # env -u unsets ambient variables rather than embedding any secret in the launcher.
    keys = sorted(set(values) | {"COMPOSE_FILE", "COMPOSE_PROFILES", "COMPOSE_PROJECT_NAME", "COMPOSE_ENV_FILES", "COMPOSE_DISABLE_ENV_FILE",
                               "DOCKER_HOST", "DOCKER_CONTEXT", "DOCKER_TLS", "DOCKER_TLS_VERIFY", "DOCKER_CERT_PATH"})
    unset = [item for key in keys for item in ("-u", key)]
    private_write(path, "#!/usr/bin/env bash\nset -euo pipefail\nexec " + shlex.join(["env"] + unset + command) + ' "$@"\n', 0o700)


def image_ready(reference, info, allow_pull, expected_id=None):
    try:
        inspected = json.loads(run(["docker", "image", "inspect", reference]))[0]
    except SetupError:
        if not allow_pull:
            raise SetupError("Missing local image: " + reference + ". Load its Docker archive or rerun with approved registry pulls enabled.")
        print("Pulling required image: " + reference)
        run(["docker", "pull", reference])
        inspected = json.loads(run(["docker", "image", "inspect", reference]))[0]
    architecture = {"x86_64": "amd64", "aarch64": "arm64"}.get(info.get("Architecture"), info.get("Architecture"))
    if inspected.get("Os") != "linux" or inspected.get("Architecture") != architecture:
        raise SetupError("Image architecture does not match this Docker host: " + reference)
    # Docker's classic store reports the config digest; containerd can report
    # the platform manifest or index digest. The packager verifies their linkage.
    expected_ids = {expected_id} if isinstance(expected_id, str) else set(expected_id or ())
    if expected_ids and inspected["Id"] not in expected_ids:
        raise SetupError("Loaded image identity differs from the bundle: " + reference)


def verify_workers(command, env, apparmor):
    for worker in WORKERS:
        print("Checking isolated actions: " + worker)
        run(command + ["run", "--rm", "--no-deps", "--pull", "never", "--entrypoint", "/opt/cats-venv/bin/python", worker, "-m", "app.rendering", "--probe"], env=env)
    ids = run(command + ["ps", "-q"] + list(WORKERS), env=env).split()
    containers = json.loads(run(["docker", "inspect"] + ids, env=env)) if ids else []
    if len(containers) != len(WORKERS):
        raise SetupError("Expected all four running action workers.")
    for container in containers:
        options = container["HostConfig"].get("SecurityOpt") or []
        if not any(option.startswith("no-new-privileges") for option in options) or not any(option.startswith("seccomp=") for option in options):
            raise SetupError("Worker is missing required seccomp/no-new-privileges protection.")
        if apparmor and container.get("AppArmorProfile") != PROFILE:
            raise SetupError("A running worker does not use the required AppArmor profile. Recreate it with the generated launcher.")


def main(argv=None):
    global DOCKER_ENDPOINT
    DOCKER_ENDPOINT = None
    if sys.version_info < (3, 9):
        raise SetupError("Python 3.9 or later is required.")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", required=True, choices=("main", "replica"))
    parser.add_argument("--env-file", type=Path, help="Existing secrets file to preserve, or new private destination")
    parser.add_argument("--configure-only", action="store_true", help="Save/check configuration without loading AppArmor, starting containers or configuring registries")
    parser.add_argument("--skip-registry", action="store_true", help="Leave post-start OCI configuration to the portal")
    parser.add_argument("--extra-compose", type=Path, action="append", default=[], help="Preserve an existing additional Compose override (repeatable)")
    args = parser.parse_args(argv)
    print("CATS " + args.mode + " setup — keep this release directory for future updates.")
    print("Upgrades: use the original environment file and project name; include custom overrides with --extra-compose.")
    manifest = verify_bundle(ROOT, args.mode)
    info = docker_host()
    DOCKER_ENDPOINT = info["_SetupEndpoint"]
    if info.get("Architecture") not in ("amd64", "x86_64"):
        raise SetupError("The full CATS image shared by main and replica currently requires a Linux amd64 host.")
    default_env = "/etc/cats/cats.env" if args.mode == "main" else "/etc/cats-replica/replica.env"
    env_file = (args.env_file or Path(ask("Private settings file (select your existing file for upgrades)", default_env))).expanduser().absolute()
    if env_file.is_symlink():
        raise SetupError("Use the real environment file path, not a symbolic link.")
    original = env_file.read_text(encoding="utf-8-sig") if env_file.exists() else None
    existing = parse_env(original) if original is not None else {}
    values = gather(args.mode, existing, manifest)
    values["CATS_SETUP_DOCKER_HOST"] = DOCKER_ENDPOINT
    ensure_no_unclaimed_project(values["COMPOSE_PROJECT_NAME"], existing)
    apparmor = apparmor_needed(args.mode, info)
    command = compose_command(args.mode, env_file, values, apparmor, args.extra_compose)
    env = clean_environment(values)
    if args.mode == "main":
        for key in ("CATS_SCAN_REGISTRY_AUTH_SOURCE", "CATS_DB_BACKUP_DIR"):
            Path(values[key]).mkdir(parents=True, exist_ok=True, mode=0o700)
        if not (Path(values["CATS_DISCOVERY_MIRROR_DIR"]) / "manifest.json").is_file():
            raise SetupError("The Discovery mirror directory requires manifest.json; retain the supplied empty mirror if unused.")
    # Keep one private rollback copy; it never rotates or replaces previous backups.
    backup = env_file.with_name(env_file.name + ".pre-setup")
    if original is not None and not backup.exists():
        private_write(backup, original)
    private_write(env_file, serialize_env(values))
    launcher = env_file.parent / ("cats-compose.sh" if args.mode == "main" else "replica-compose.sh")
    write_launcher(launcher, command, values)
    run(command + ["config", "--quiet"], env=env)
    print("Private settings saved: " + str(env_file))
    print("Administrator username: " + values["CATS_BOOTSTRAP_USERNAME"] + "; initial password is in that private settings file.")
    print("Future updates/status: sudo bash " + shlex.quote(str(launcher)) + " <compose arguments>")
    if args.configure_only:
        print("Configuration checked. No images loaded, AppArmor profiles changed, containers started or OCI settings submitted.")
        return 0
    if (ROOT / "images.tar").is_file() and "images.tar" in manifest.get("files", {}):
        if yes("Load the verified images.tar from this bundle?"):
            print("Loading bundle images; large archives can take several minutes.")
            run(["docker", "load", "--input", ROOT / "images.tar"])
    allow_pull = yes("Allow pulling missing images from their registries? Choose no for disconnected setup", default=False)
    references = run(command + ["config", "--images"], env=env).splitlines()
    expected = {row["archive_reference"]: tuple(row[key] for key in
                ("image_id", "image_manifest_id", "image_config_id") if row.get(key))
                for row in manifest.get("images", []) if row.get("archive_reference")}
    for reference in dict.fromkeys(references):
        image_ready(reference, info, allow_pull, expected.get(reference))
    if apparmor:
        load_apparmor()
    print("Starting services and waiting for their health checks. Initial intelligence loading can take several minutes.")
    run(command + ["up", "-d", "--no-build", "--pull", "never", "--wait", "--wait-timeout", "900"], env=env)
    if args.mode == "main":
        verify_workers(command, env, apparmor)
    portal_url = "https://" + values["CATS_PORTAL_HOSTNAME"]
    print("Containers are healthy. Portal: " + portal_url + "; OCI: https://" + values["CATS_OCI_HOSTNAME"])
    if args.skip_registry:
        print("OCI setup is pending: configure registry, signing/publisher trust and consumer grants in the portal.")
    else:
        from cats_setup_registry import configure_registry, SetupError as RegistrySetupError
        try:
            configure_registry(args.mode, portal_url, values["CATS_BOOTSTRAP_USERNAME"], values["CATS_BOOTSTRAP_PASSWORD"],
                               ca_file=values.get("CATS_SETUP_CA_FILE") or None,
                               image=values["CATS_IMAGE"] if args.mode == "main" else None,
                               state_dir=str(env_file.parent), docker_endpoint=DOCKER_ENDPOINT)
        except RegistrySetupError as exc:
            raise SetupError("Containers remain running; OCI configuration needs attention. " + str(exc)) from None
    print("Before operational use, test an approved pull through the OCI hostname from a client that trusts its CA.")
    if args.mode == "main":
        print("Confirm scanner databases are ready, run a real scan/approval/publication, and provision a separate validator if required by your delivery policy.")
    else:
        print("Replicate the complete release graph into the local registry, synchronize it, then test a pull with the source disconnected.")
    return 0


