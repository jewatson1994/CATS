"""Trusted, retained inputs for an isolated Copa worker.

The specification is worker-local deployment configuration, never request JSON.
Repository/registry services must expose read-only bind-mounted snapshots and
have only an internal Docker network. Each preparation starts a fresh BuildKit
cache on that network; no upstream fallback is reachable from build execution.
"""
from __future__ import annotations
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tarfile
import urllib.parse
import urllib.request
import uuid
import importlib.metadata
import sysconfig

from .scanner_inputs import snapshot_digest
from .patch_ownership import execution_lock


def _digest(value):
    return "sha256:" + hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def _file_digest(path):
    path = Path(path).resolve(strict=True)
    if not path.is_file():
        raise ValueError("Bound engine input must be a regular file")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def system_ca_bundle():
    """The exact system trust text used by the patch worker."""
    candidates = [Path('/etc/ssl/certs/ca-certificates.crt')]
    try:
        import certifi
        candidates.append(Path(certifi.where()))
    except ImportError:
        pass
    for path in candidates:
        if path.is_file():
            text = path.read_text(encoding='utf-8')
            if not text.strip():
                raise ValueError('Patch worker system CA bundle is unavailable')
            return text
    raise ValueError('Patch worker system CA bundle is unavailable')


def _python_runtime_identity():
    """Hash installed content, never trust package version/RECORD assertions.

    Generated bytecode is omitted because Python validates it against source;
    this assumes a trusted interpreter and deployment filesystem. Editable
    installs cannot establish a complete installed-file inventory.
    """
    packages = []
    for distribution in importlib.metadata.distributions():
        direct = distribution.read_text('direct_url.json')
        if direct and json.loads(direct).get('dir_info', {}).get('editable'):
            raise ValueError('Bound execution does not support editable dependencies')
        files = distribution.files
        if files is None:
            raise ValueError('Installed Python dependency has no file inventory')
        contents = {}
        for relative in files:
            if str(relative).endswith(('.pyc', '.pyo')):
                continue
            contents[str(relative).replace('\\', '/')] = _file_digest(distribution.locate_file(relative))
        packages.append({'name': distribution.metadata['Name'], 'version': distribution.version,
                         'files': contents})
    stdlib = Path(sysconfig.get_path('stdlib')).resolve()
    library = {}
    for directory, dirs, files in os.walk(stdlib):
        dirs[:] = sorted(name for name in dirs if name not in {'__pycache__', 'site-packages', 'dist-packages'})
        for name in sorted(files):
            if name.endswith(('.pyc', '.pyo')):
                continue
            path = Path(directory) / name
            library[path.relative_to(stdlib).as_posix()] = _file_digest(path)
    return _digest({'implementation': sys.implementation.name, 'version': sys.version,
                    'stdlib': library, 'packages': sorted(packages, key=lambda item: (item['name'], item['version']))})


def _docker(*args):
    result = subprocess.run(["docker", *args], check=True, capture_output=True, text=True, timeout=60)
    return result.stdout.strip()


def _inspect(kind, name):
    return json.loads(_docker(kind, "inspect", name))[0]


def _config(config):
    return {key: value for key, value in config.items() if key != "execution_binding"}


def _scanner_max_age(spec):
    value = spec.get("scanner_max_age_hours", 120)
    if type(value) is not int or not 1 <= value <= 8760:
        raise ValueError("Scanner maximum age must be between 1 and 8760 hours")
    return value


def _runtime(spec):
    network = _inspect("network", spec["network"])
    if network.get("Internal") is not True or network.get("Driver") != "bridge":
        raise ValueError("Bound execution requires an internal Docker bridge")
    services = []
    for name in spec["services"]:
        item = _inspect("container", name)
        host = item["HostConfig"]
        if (set(item["NetworkSettings"]["Networks"]) != {spec["network"]}
                or host.get("Privileged") or host.get("NetworkMode") == "host"
                or host.get("VolumesFrom") or host.get("Devices") or host.get("CapAdd")):
            raise ValueError("Snapshot service is not isolated")
        mounts = []
        for mount in item.get("Mounts", []):
            if mount.get("Type") != "bind" or mount.get("RW"):
                raise ValueError("Snapshot service requires only read-only bind mounts")
            # Docker mount source paths belong to the daemon host, which may
            # differ from this worker filesystem. Hash bytes copied from the
            # actual serving container instead of assuming host path identity.
            with tempfile.TemporaryDirectory(prefix="cats-input-check-") as temporary:
                retained = Path(temporary) / "input"
                _docker("cp", name + ":" + mount["Destination"], str(retained))
                mounts.append([mount["Destination"], snapshot_digest(retained) if retained.is_dir() else _file_digest(retained)])
        if not host.get("ReadonlyRootfs") or not item["State"].get("Running"):
            raise ValueError("Snapshot service must be running with retained inputs")
        services.append({"image": item["Image"], "command": item["Config"].get("Cmd"),
                         "entrypoint": item["Config"].get("Entrypoint"), "environment": item["Config"].get("Env"),
                         "mounts": sorted(mounts)})
    # Hash executable bytes, not version strings or operator-provided digests.
    engines = {}
    for name in ("copa", "grype", "syft", "cosign", "docker", "trivy", "dockle"):
        path = shutil.which(name)
        if not path and name in {"trivy", "dockle"}:
            engines[name] = None
            continue
        if not path:
            raise ValueError("Required bound engine executable is unavailable: " + name)
        engines[name] = _file_digest(path)
    engines["python"] = _file_digest(sys.executable)
    engines["python_runtime"] = _python_runtime_identity()
    engines["system_ca_bundle"] = hashlib.sha256(system_ca_bundle().encode("utf-8")).hexdigest()
    engines["worker_sources"] = {path.name: _file_digest(path) for path in sorted(Path(__file__).parent.glob("*.py"))}
    image = _inspect("image", spec["buildkit_image"])
    engines["buildkit_image"] = image["Id"]
    engines["services"] = services
    engines["buildkit_config"] = _file_digest(spec["buildkit_config"])
    engines["privileged_buildkit"] = spec.get("privileged_buildkit") is True
    engines["scanner_max_age_hours"] = _scanner_max_age(spec)
    if spec.get("staging_registry"):
        stage = _inspect("container", spec["staging_registry"]["container"])
        if (set(stage["NetworkSettings"]["Networks"]) != {spec["network"]} or
                stage["HostConfig"].get("Privileged") or stage["HostConfig"].get("Devices")
                or stage["HostConfig"].get("VolumesFrom") or stage["HostConfig"].get("CapAdd")
                or not stage["State"].get("Running")):
            raise ValueError("Source staging registry must be isolated")
        address = stage["NetworkSettings"]["Networks"][spec["network"]]
        hosts = {address["IPAddress"], *(address.get("Aliases") or [])}
        endpoints = (urllib.parse.urlsplit(spec["staging_registry"]["upload_url"]),
                     urllib.parse.urlsplit("http://" + spec["staging_registry"]["pull_prefix"]))
        if any(endpoint.hostname not in hosts or endpoint.username or endpoint.password for endpoint in endpoints):
            raise ValueError("Source staging endpoint must address the isolated registry container")
        engines["source_staging"] = {"image": stage["Image"], "configuration": spec["staging_registry"]}
    return engines


def prepare_binding(config, binding_root):
    """Return a worker-issued handle and identity, or None for an unbound worker."""
    specification = os.getenv("CATS_PATCH_BINDING_SPEC")
    if not specification:
        return None
    spec = json.loads(Path(specification).read_text(encoding="utf-8"))
    if spec.get("schema") != "cats-isolated-copa-v1":
        raise ValueError("Unsupported isolated worker specification")
    if not isinstance(spec.get("staging_registry"), dict) or not all(
            spec["staging_registry"].get(key) for key in ("container", "upload_url", "pull_prefix")):
        raise ValueError("Bound Copa requires an isolated source staging registry")
    if not isinstance(config.get("destination_scope"), dict) or not config["destination_scope"].get("host"):
        raise ValueError("Prepared execution requires an explicit destination scope")
    if (config.get("source_mode") != "oci" or not re.fullmatch(r"[^\s@]+@sha256:[0-9a-f]{64}", str(config.get("source_image")))
            or config.get("repository_policies") != spec.get("repository_policies")):
        raise ValueError("Patch configuration does not match retained repository inputs")
    if config.get("remediation_evidence") and shutil.which("trivy") and not spec.get("trivy_root"):
        raise ValueError("Remediation evidence requires a retained Trivy database")
    engines = _runtime(spec)
    root = Path(binding_root) / uuid.uuid4().hex
    root.mkdir(parents=True, mode=0o700)
    try:
        scanner_digest = snapshot_digest(spec["scanner_root"])
        shutil.copytree(spec["scanner_root"], root / "scanner")
        if snapshot_digest(root / "scanner") != scanner_digest:
            raise ValueError("Scanner input changed during preparation")
        auxiliary = {}
        if spec.get("trivy_root"):
            auxiliary["trivy"] = snapshot_digest(spec["trivy_root"])
            shutil.copytree(spec["trivy_root"], root / "trivy")
            if snapshot_digest(root / "trivy") != auxiliary["trivy"]:
                raise ValueError("Trivy database changed during preparation")
        engines["auxiliary_scanners"] = auxiliary
        repository_digest = _digest({"repository": snapshot_digest(spec["repository_root"]),
                                     "registry": snapshot_digest(spec["registry_root"])})
        identity = {"schema": "cats-patch-inputs-v1", "engine_digest": _digest(engines),
                    "repository_snapshot_digest": repository_digest, "scanner_database_digest": scanner_digest}
        # A new daemon has no untracked helper images or stale mutable tag cache.
        name = "cats-bound-" + root.name
        privileges = ["--privileged"] if spec.get("privileged_buildkit") is True else []
        _docker("create", *privileges, "--name", name, "--network", spec["network"],
                "--entrypoint", "buildkitd", engines["buildkit_image"],
                "--config", "/tmp/cats-buildkitd.toml", "--addr", "tcp://0.0.0.0:1234", "--oci-worker-net", "host", "--oci-worker-snapshotter", "native", "--containerd-worker=false")
        _docker("cp", str(Path(spec["buildkit_config"]).resolve()), name + ":/tmp/cats-buildkitd.toml")
        _docker("start", name)
        runtime = _inspect("container", name)
        address = "tcp://" + runtime["NetworkSettings"]["Networks"][spec["network"]]["IPAddress"] + ":1234"
        manifest = {"auxiliary_scanners": auxiliary, "config": _config(config), "spec": spec, "identity": identity,
                    "buildkit_container": name, "buildkit_id": runtime["Id"], "buildkit_addr": address}
        (root / "manifest.json").write_text(json.dumps(manifest, sort_keys=True), encoding="utf-8")
        return {"binding_id": root.name, "identity": identity}
    except Exception:
        # A failed preparation has never been used for publication.
        try:
            _docker("rm", "-f", "cats-bound-" + root.name)
        except Exception:
            pass
        raise


class ExecutionBinding:
    def __init__(self, root, manifest):
        self.root, self.manifest = root, manifest
        self.identity = manifest["identity"]
        self.scanner_root = root / "scanner"
        self.buildkit_addr = manifest["buildkit_addr"]

    def verify(self):
        spec = self.manifest["spec"]
        engines = _runtime(spec)
        engines["auxiliary_scanners"] = {name: snapshot_digest(self.root / name)
                                         for name in self.manifest.get("auxiliary_scanners", {})}
        if (_digest(engines) != self.identity["engine_digest"]
                or snapshot_digest(self.scanner_root) != self.identity["scanner_database_digest"]
                or _digest({"repository": snapshot_digest(spec["repository_root"]), "registry": snapshot_digest(spec["registry_root"])}) != self.identity["repository_snapshot_digest"]):
            raise RuntimeError("Prepared execution inputs changed")
        runtime = _inspect("container", self.manifest["buildkit_container"])
        if (runtime["Id"] != self.manifest["buildkit_id"] or not runtime["State"].get("Running")
                or set(runtime["NetworkSettings"]["Networks"]) != {spec["network"]}
                or runtime.get("Mounts")
                or bool(runtime["HostConfig"].get("Privileged")) != bool(spec.get("privileged_buildkit"))):
            raise RuntimeError("Prepared BuildKit execution isolation changed")

    def stage_source(self, reference):
        """Deliver the worker-created overlay to the isolated resolver by digest.

        No Docker-daemon tag is assumed visible inside a separate BuildKit.
        The staging registry contains derived source images only; retained helper
        registries remain read-only and part of the prepared repository identity.
        """
        self.verify()
        stage = self.manifest["spec"].get("staging_registry")
        if not stage:
            raise RuntimeError("Bound Copa requires an isolated source staging registry")
        repository = "cats-source-" + self.root.name
        archive = self.root / "source.tar"
        _docker("save", "--output", str(archive), reference)
        base = stage["upload_url"].rstrip("/")
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, req, fp, code, msg, headers, newurl):
                raise RuntimeError("Staging registry HTTP redirects are forbidden")
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())

        def request(path, data=None, method="POST", headers=None):
            target = urllib.parse.urljoin(base + "/", path)
            if urllib.parse.urlsplit(target).netloc != urllib.parse.urlsplit(base).netloc:
                raise RuntimeError("Staging registry attempted an external upload redirect")
            return opener.open(urllib.request.Request(target, data=data, method=method, headers=headers or {}), timeout=120)

        def upload(bundle, name, media):
            member = bundle.getmember(name)
            if not member.isfile():
                raise ValueError("Image archive contains a non-file blob")
            digest = hashlib.sha256()
            with bundle.extractfile(member) as stream:
                for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(chunk)
            identity = "sha256:" + digest.hexdigest()
            with request("/v2/" + repository + "/blobs/uploads/", data=b"") as response:
                location = response.headers["Location"]
            separator = "&" if "?" in location else "?"
            with bundle.extractfile(member) as stream:
                with request(location + separator + "digest=" + identity, data=stream, method="PUT",
                             headers={"Content-Type": "application/octet-stream", "Content-Length": str(member.size)}) as response:
                    if response.headers.get("Docker-Content-Digest") != identity:
                        raise RuntimeError("Staging registry did not retain the exact source blob")
            return {"mediaType": media, "digest": identity, "size": member.size}

        def upload_layer(bundle, name):
            with bundle.extractfile(name) as stream:
                magic = stream.read(4)
            media = "application/vnd.oci.image.layer.v1.tar"
            if magic.startswith(b"\x1f\x8b"):
                media += "+gzip"
            elif magic == b"\x28\xb5\x2f\xfd":
                media += "+zstd"
            return upload(bundle, name, media)

        try:
            with tarfile.open(archive, "r") as bundle:
                manifests = json.load(bundle.extractfile("manifest.json"))
                if len(manifests) != 1:
                    raise ValueError("Bound source must contain exactly one image")
                source = manifests[0]
                manifest = {"schemaVersion": 2, "mediaType": "application/vnd.oci.image.manifest.v1+json",
                            "config": upload(bundle, source["Config"], "application/vnd.oci.image.config.v1+json"),
                            "layers": [upload_layer(bundle, layer) for layer in source["Layers"]]}
            payload = json.dumps(manifest, separators=(",", ":")).encode()
            digest = "sha256:" + hashlib.sha256(payload).hexdigest()
            with request("/v2/" + repository + "/manifests/prepared", data=payload, method="PUT",
                         headers={"Content-Type": manifest["mediaType"]}) as response:
                if response.headers.get("Docker-Content-Digest") != digest:
                    raise RuntimeError("Staging registry did not retain the exact source manifest")
            self.verify()
            return stage["pull_prefix"].rstrip("/") + "/" + repository + "@" + digest
        finally:
            archive.unlink(missing_ok=True)

    def close(self):
        _docker("rm", "-f", self.manifest["buildkit_id"])
        (self.root / "finished").touch()

    def receipt(self, config, destination):
        self.verify()
        return {"schema": "cats-patch-consumed-inputs-v1", "job_id": config["job_id"],
                "source_image": config["source_image"], "immutable_destination": destination,
                "identity": self.identity, "config": _config(config),
                "destination_scope": config["destination_scope"]}


def consume_binding(config, binding_root):
    handle = config.get("execution_binding")
    if handle is None:
        return None
    if not isinstance(handle, str) or not re.fullmatch(r"[0-9a-f]{32}", handle):
        raise ValueError("Invalid execution binding")
    root = Path(binding_root) / handle
    with execution_lock(root / "admission.lock"):
        if (root / "released").exists():
            raise ValueError("Execution binding was released")
        manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
        if manifest["config"] != _config(config):
            raise ValueError("Prepared configuration differs from execution")
        binding = ExecutionBinding(root, manifest)
        binding.verify()
        # A binding is an execution reservation, never transferable or replayable.
        with (root / "consumed").open("x", encoding="utf-8") as stream:
            stream.write(config["job_id"])
        return binding



def default_binding_root():
    return Path(os.getenv("CATS_PATCH_BINDING_ROOT") or
                str(Path(os.getenv("CATS_PATCH_JOB_ROOT", str(Path(tempfile.gettempdir()) / "cats-patch-jobs"))) / "bindings"))


def release_binding(handle, binding_root):
    """Release an unused preparation; never interrupt a consumed execution."""
    if not isinstance(handle, str) or not re.fullmatch(r"[0-9a-f]{32}", handle):
        raise ValueError("Invalid execution binding")
    root = Path(binding_root) / handle
    with execution_lock(root / "admission.lock"):
        if (root / "consumed").exists():
            raise ValueError("Execution binding has already been consumed")
        manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
        _docker("rm", "-f", manifest["buildkit_id"])
        (root / "released").touch()
